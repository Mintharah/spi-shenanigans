/* ═══════════════════════════════════════════════════════════════════════════
 *  main()
 * ═══════════════════════════════════════════════════════════════════════════ */
int main(void)
{
    HAL_Init();
    SystemClock_Config();
    MX_GPIO_Init();
    MX_DMA_Init();   /* MUST come before MX_SPI2_Init — DMA clocks must be
                      * enabled before the SPI peripheral binds its streams. */
    MX_SPI2_Init();  /* CubeMX-generated; ensure it sets:
                      *   hspi2.Init.NSS = SPI_NSS_HARD_INPUT  (SSM=0)
                      * If CubeMX generated SPI_NSS_SOFT, change it in the
                      * CubeMX GUI (SPI2 → Parameter Settings →
                      * NSS Signal Type → Hardware NSS Input Signal) and
                      * re-generate, or edit the Init struct directly here. */

    /* Arm the very first transfer — slave is now ready before the master
     * sends anything.  All subsequent re-arms happen inside the callback. */
    arm_transfer();

    while (1)
    {
        /* Nothing to do in the main loop.
         * All SPI work happens in HAL_SPI_TxRxCpltCallback().
         * You can add LED heartbeats, UART logging, etc. here. */
    }
}

/* ═══════════════════════════════════════════════════════════════════════════
 *  SystemClock_Config()  — generated by CubeMX, do not edit by hand
 * ═══════════════════════════════════════════════════════════════════════════ */
void SystemClock_Config(void)
{
    RCC_OscInitTypeDef osc = {0};
    RCC_ClkInitTypeDef clk = {0};
 
    /* Scale 2 is required to reach 84 MHz on the F401. */
    __HAL_RCC_PWR_CLK_ENABLE();
    __HAL_PWR_VOLTAGESCALING_CONFIG(PWR_REGULATOR_VOLTAGE_SCALE2);
 
    /* HSI on, PLL on. PLLQ=7 -> 48 MHz (only matters if you use USB OTG/SDIO,
     * but it must still be a valid divider). */
    osc.OscillatorType      = RCC_OSCILLATORTYPE_HSI;
    osc.HSIState            = RCC_HSI_ON;
    osc.HSICalibrationValue = RCC_HSICALIBRATION_DEFAULT;
    osc.PLL.PLLState        = RCC_PLL_ON;
    osc.PLL.PLLSource       = RCC_PLLSOURCE_HSI;
    osc.PLL.PLLM            = 16;
    osc.PLL.PLLN            = 336;
    osc.PLL.PLLP            = RCC_PLLP_DIV4;
    osc.PLL.PLLQ            = 7;
    if (HAL_RCC_OscConfig(&osc) != HAL_OK) {
        Error_Handler();                /* don't silently run at the wrong clock */
    }
 
    /* Switch SYSCLK to the PLL and set the bus prescalers.
     * AHB /1 = 84, APB1 /2 = 42 (must be <= 42), APB2 /1 = 84.
     * FLASH_LATENCY_2 is applied here, before the clock is raised. */
    clk.ClockType      = RCC_CLOCKTYPE_HCLK   | RCC_CLOCKTYPE_SYSCLK
                       | RCC_CLOCKTYPE_PCLK1  | RCC_CLOCKTYPE_PCLK2;
    clk.SYSCLKSource   = RCC_SYSCLKSOURCE_PLLCLK;
    clk.AHBCLKDivider  = RCC_SYSCLK_DIV1;
    clk.APB1CLKDivider = RCC_HCLK_DIV2;
    clk.APB2CLKDivider = RCC_HCLK_DIV1;
    if (HAL_RCC_ClockConfig(&clk, FLASH_LATENCY_2) != HAL_OK) {
        Error_Handler();
    }
 
    /* After this, SystemCoreClock == 84000000. Anything that latched a timing
     * value off the old 16 MHz (e.g. a cached SystemCoreClock, UART baud, or a
     * TIM prescaler computed earlier) must be re-derived from 84 MHz. */
}


