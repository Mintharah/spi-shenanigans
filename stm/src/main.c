/* ═══════════════════════════════════════════════════════════════════════════
 *  fill_test_data()
 *
 *  Refresh g_tx_data with "live" values.
 *  Called from arm_transfer() before every re-arm, so each master read
 *  gets an up-to-date snapshot.
 * ═══════════════════════════════════════════════════════════════════════════ */
static void fill_test_data(void)
{
    g_tx_data.field1 = (uint16_t)(1000 + g_transfer_count); /* counts up      */
    g_tx_data.field2 = 2000;
    g_tx_data.field3 = -250;                                 /* e.g. -25.0 °C  */
    g_tx_data.field4 = 3300;                                 /* e.g. 3.300 V   */
    g_tx_data.field5 = 0x01;                                 /* status flags   */
    g_tx_data.field6 = 1500;                                 /* RPM            */
    g_tx_data.field7 = HAL_GetTick();                        /* ms uptime      */
}

/* ═══════════════════════════════════════════════════════════════════════════
 *  arm_transfer()
 *
 *  Refresh TX data, then arm a single sizeof(stm32_data_t) DMA transfer.
 *  Call once at init and once at the end of every TxRxCpltCallback.
 *
 *  Using DMA (not IT) keeps the re-arm latency in the nanosecond range,
 *  so there is virtually no idle window on MISO between transfers.
 *
 *  REQUIREMENT: MX_DMA_Init() must be called before MX_SPI2_Init() in
 *  main() — CubeMX does this automatically when DMA is enabled for SPI2.
 * ═══════════════════════════════════════════════════════════════════════════ */
static void arm_transfer(void)
{
    fill_test_data();
    memset(g_rx_sink, 0, sizeof(g_rx_sink));

    // Call this ONCE. The circular DMA will keep it alive forever.
    HAL_StatusTypeDef status =
        HAL_SPI_TransmitReceive_DMA(SLAVE_SPI_HANDLE,
                                    (uint8_t *)&g_tx_data,
                                    g_rx_sink,
                                    sizeof(stm32_data_t));

}

/* ═══════════════════════════════════════════════════════════════════════════
 *  HAL_SPI_TxRxCpltCallback()
 *
 *  Fires when the DMA-driven TransmitReceive finishes (all 15 bytes sent
 *  and received).  Same callback name as the IT version — HAL uses it for
 *  both modes.  We count the transfer and immediately re-arm.
 *
 *  CubeMX declares a weak stub in stm32xxxx_it.c.  If you already have a
 *  non-weak definition there, merge this body into it.
 * ═══════════════════════════════════════════════════════════════════════════ */
void HAL_SPI_TxRxCpltCallback(SPI_HandleTypeDef *hspi)
{
    if (hspi->Instance != SLAVE_SPI_HANDLE->Instance)
        return;

    g_transfer_count++;

    /* * ONLY update the data. The DMA hardware has already wrapped 
     * around and is ready to send this fresh data on the next clock.
     */
    fill_test_data(); 
}

/* ═══════════════════════════════════════════════════════════════════════════
 *  HAL_SPI_ErrorCallback()
 *
 *  Fires on overrun, CRC, mode-fault, or DMA errors.  We abort any
 *  in-flight DMA, clear the overrun flag, then re-arm.
 *
 *  HAL_SPI_DMAStop() is safe to call even if no DMA is active.
 * ═══════════════════════════════════════════════════════════════════════════ */
void HAL_SPI_ErrorCallback(SPI_HandleTypeDef *hspi)
{
    if (hspi->Instance != SLAVE_SPI_HANDLE->Instance)
    {
        return;
    }

    g_error_count++;

    /* Stop any in-flight DMA streams before touching the peripheral */
    HAL_SPI_DMAStop(hspi);

    /* Clear overrun — mandatory before the next TransmitReceive arm */
    __HAL_SPI_CLEAR_OVRFLAG(hspi);

    arm_transfer();
}

