/* ─────────────────────────────────────────────────────────────────────────
 * stm32_data_t — must EXACTLY match the RPi5 side:
 *   same field order, same types, same packing, same total size (15 bytes).
 *
 *   Verification:
 *     static_assert(sizeof(stm32_data_t) == 15, "struct size mismatch");
 * ───────────────────────────────────────────────────────────────────────── */
#pragma pack(push, 1)
typedef struct
{
    uint16_t field1; /* e.g. sensor A raw ADC          */
    uint16_t field2; /* e.g. sensor B raw ADC          */
    int16_t  field3; /* e.g. signed temperature × 10  */
    uint16_t field4; /* e.g. voltage × 100 mV          */
    uint8_t  field5; /* e.g. status flags              */
    uint16_t field6; /* e.g. RPM                        */
    uint32_t field7; /* e.g. millisecond timestamp     */
} stm32_data_t;
#pragma pack(pop)

