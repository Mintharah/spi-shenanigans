/* SPI handle generated by CubeMX — adjust if you used a different instance */
extern SPI_HandleTypeDef hspi2;
#define SLAVE_SPI_HANDLE (&hspi2)

/* ─── TX buffer ─────────────────────────────────────────────────────────────
 * g_tx_data is the DMA source — it MUST remain valid for the full duration
 * of the transfer.  Declared static (not on the stack) to guarantee this.
 * fill_test_data() writes it only from HAL_SPI_TxRxCpltCallback(), which
 * fires after DMA completes, so there is no write/read overlap.
 *
 * If your MCU requires DMA buffers in a specific RAM region (e.g. SRAM1 on
 * STM32H7), add  __attribute__((section(".dma_buffer")))  here and configure
 * the linker script accordingly.  Not needed for STM32F4.
 * ─────────────────────────────────────────────────────────────────────────── */
static volatile stm32_data_t g_tx_data;

/* Dummy sink for the master's outgoing bytes — we don't use them */
static uint8_t g_rx_sink[sizeof(stm32_data_t)];

/* Diagnostics */
static volatile uint32_t g_transfer_count = 0; /* completed transfers */
static volatile uint32_t g_error_count    = 0; /* HAL errors seen     */

/* USER CODE END PV */

